# Built-in functions
# Matthew Woods - practice file

fam = [1.73, 1.68, 1.71, 1.89]

# len() - number of items
print(len(fam))

# max() and min()
print(max(fam))
print(min(fam))

# round() - second argument is decimal places
print(round(1.68, 1))
print(round(1.68))

# type() - check what something is
print(type(fam))
print(type("hello"))
print(type(5))

# sorted() - returns a new sorted list
full = [11.25, 18.0, 20.0, 10.75, 9.50]
print(sorted(full))
print(sorted(full, reverse=True))
print(sorted(full, reverse=True))
