# String methods
place = "poolhouse"

# upper() - all capitals
print(place.upper())

# count() - how many times a character appears
print(place.count("o"))

# replace() - swap one bit of text for another
print(place.replace("pool", "bath"))

# List methods on strings vs lists
areas = [11.25, 18.0, 20.0, 10.75, 9.50]

# index() - position of a value
print(areas.index(20.0))

# count() - works on lists too
print(areas.count(14.5))
